#!/usr/bin/env python3
"""Generate C layouts and owned Rust conversions from the reviewed API schema."""

import argparse
import json
import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import TypedDict, cast

PRIMITIVES = {
    "u8": "uint8_t",
    "u16": "uint16_t",
    "u32": "uint32_t",
    "u64": "uint64_t",
    "i32": "int32_t",
    "i64": "int64_t",
    "usize": "size_t",
    "f64": "double",
}


def snake(value: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower()


def retain_functions(text: str, roots: set[str]) -> str:
    """Keep generated helpers reachable from the declared public payloads."""
    functions = {}
    for match in re.finditer(r"(?:pub\(crate\) )?(?:unsafe )?fn (\w+)[^{]*\{", text):
        depth = 1
        end = match.end()
        while depth:
            depth += (text[end] == "{") - (text[end] == "}")
            end += 1
        functions[match[1]] = (match.start(), end, text[match.end() : end])
    needed = set(roots)
    while True:
        previous = needed.copy()
        for name in previous:
            if name in functions:
                needed.update(re.findall(r"\b(\w+)(?:\s*::<[^>]*>)?\s*\(", functions[name][2]))
        if previous == needed:
            break
    for name, (start, end, _) in sorted(
        functions.items(), key=lambda item: item[1][0], reverse=True
    ):
        if name not in needed:
            text = text[:start] + text[end:]
    return text


class TypeDefinition(TypedDict):
    """Reviewed native Rust type and ordered named fields."""

    rust: str
    fields: list[list[str]]


class Schema(TypedDict):
    """JSON boundary for generated layouts and ownership conversions."""

    name: str
    types: dict[str, TypeDefinition]
    enums: dict[str, list[str]]
    outputs: list[str]


def generate_layouts(schema: Schema) -> tuple[list[str], list[str]]:
    name = schema["name"]
    types = schema["types"]
    enums = schema["enums"]
    prefix = "peios_" + name + "_"
    layouts = {
        "Bytes": [("data", "*const u8"), ("len", "usize")],
        "Strings": [("data", "*const Bytes"), ("len", "usize")],
        "OptionalU16": [("present", "u32"), ("value", "u16")],
    }

    def kind(t: str) -> str:
        if t in ("String", "Option<String>", "IpAddr", "Vec<u8>"):
            return "Bytes"
        if t == "Vec<String>":
            return "Strings"
        if t == "Option<u16>":
            return "OptionalU16"
        if t == "bool" or t in enums:
            return "u32"
        if t.startswith("Vec<"):
            return t[4:-1] + "List"
        return t

    # Arrays are forward declared in C. Rust does not require declaration order.
    for typ, definition in types.items():
        layouts[typ] = [(field, kind(t)) for field, t in definition["fields"]]
        layouts[typ + "List"] = [("data", "*const " + typ), ("len", "usize")]

    def ctype(t: str) -> str:
        if t.startswith("*const "):
            return "const " + ctype(t[7:]) + " *"
        return PRIMITIVES.get(t, prefix + snake(t))

    header = [
        "/* Generated by tools/generate-api-types.py. */",
        f"#ifndef PEIOS_{name.upper()}_TYPES_H",
        f"#define PEIOS_{name.upper()}_TYPES_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
    ]
    for typ in layouts:
        header.append(f"typedef struct {prefix + snake(typ)} {prefix + snake(typ)};")
    # Define data structures before the structures that contain them by value.
    pending = dict(layouts)
    ordered = {}
    while pending:
        before = len(pending)
        for typ, fields in list(pending.items()):
            if all(t.startswith("*") or t in PRIMITIVES or t in ordered for _, t in fields):
                ordered[typ] = fields
                del pending[typ]
        if len(pending) == before:
            raise ValueError("schema has unknown or cyclic by-value fields")
    rust = ["//! Generated C layouts. See the installed header for ownership contracts."]
    for typ, fields in ordered.items():
        rust += (
            ["#[repr(C)]", "#[derive(Clone, Copy)]", f"pub struct {typ} {{"]
            + [f"    pub {field}: {t}," for field, t in fields]
            + ["}"]
        )
        header += (
            ["struct " + prefix + snake(typ) + " {"]
            + [f"    {ctype(t)} {field};" for field, t in fields]
            + ["};"]
        )
    for typ, variants in enums.items():
        header += [
            f"#define {prefix.upper() + snake(typ).upper() + '_' + snake(v).upper()} {i}u"
            for i, v in enumerate(variants)
        ]
    header += ["#endif"]
    return rust, header


def generate_helpers(schema: Schema) -> tuple[list[str], list[str]]:
    abi = schema["name"].replace("-", "_") + "_abi"
    view = [
        "//! Generated stable storage and C views.",
        "use std::any::Any;",
        f"use {abi} as abi;",
        "#[derive(Default)]",
        "pub(crate) struct Arena { allocations: Vec<Box<dyn Any>> }",
        "pub(crate) fn absent() -> abi::Bytes { abi::Bytes { data: std::ptr::null(), len: 0 } }",
        "impl Arena {",
        "pub(crate) fn bytes(&mut self, value: &[u8]) -> abi::Bytes {",
        "let owned = value.to_vec().into_boxed_slice(); let result = abi::Bytes { data: owned.as_ptr(), len: owned.len() };",
        "self.allocations.push(Box::new(owned)); result }",
        "pub(crate) fn text(&mut self, value: &str) -> abi::Bytes { self.bytes(value.as_bytes()) }",
        "pub(crate) fn maybe_text(&mut self, value: Option<&str>) -> abi::Bytes { value.map_or_else(absent, |value| self.text(value)) }",
        "pub(crate) fn strings(&mut self, values: &[String]) -> abi::Strings {",
        "let owned: Box<[_]> = values.iter().map(|value| self.text(value)).collect();",
        "let result = abi::Strings { data: owned.as_ptr(), len: owned.len() }; self.allocations.push(Box::new(owned)); result }",
    ]
    decode = [
        "//! Generated owned copies of views borrowed from a live library result.",
        f"use {abi} as abi;",
        "use crate::{Error, invalid};",
        "pub(crate) unsafe fn array<'a, T>(data: *const T, len: usize) -> &'a [T] {",
        "if len == 0 { return &[]; }",
        "// SAFETY: caller borrows a validated array from a live ABI result for this lifetime.",
        "unsafe { std::slice::from_raw_parts(data, len) } }",
        "pub(crate) unsafe fn bytes(value: abi::Bytes) -> Vec<u8> {",
        "// SAFETY: the span is borrowed from a live result for this copy.",
        "unsafe { array(value.data, value.len) }.to_vec() }",
        "pub(crate) unsafe fn text(value: abi::Bytes) -> Result<String, Error> {",
        "// SAFETY: the caller keeps the owning result alive.",
        'String::from_utf8(unsafe { bytes(value) }).map_err(|_| invalid("invalid library UTF-8")) }',
        "pub(crate) unsafe fn maybe_text(value: abi::Bytes) -> Result<Option<String>, Error> {",
        "if value.data.is_null() { return Ok(None); }",
        "// SAFETY: the caller keeps the owning result alive.",
        "unsafe { text(value) }.map(Some) }",
        "pub(crate) unsafe fn strings(value: abi::Strings) -> Result<Vec<String>, Error> {",
        "// SAFETY: all nested spans are owned by the same live result.",
        "unsafe { array(value.data, value.len) }.iter().map(|value| unsafe { text(*value) }).collect() }",
    ]

    return view, decode


def encode_expr(schema: Schema, t: str, v: str) -> str:
    name, types, enums = schema["name"], schema["types"], schema["enums"]
    if t == "String":
        return f"self.text(&{v})"
    if t == "IpAddr":
        return f"self.text(&{v}.to_string())"
    if t == "Option<String>":
        return f"self.maybe_text({v}.as_deref())"
    if t == "Vec<u8>":
        return f"self.bytes(&{v})"
    if t == "Vec<String>":
        return f"self.strings(&{v})"
    if t == "Option<u16>":
        return f"abi::OptionalU16 {{ present: u32::from({v}.is_some()), value: {v}.unwrap_or(0) }}"
    if t == "bool":
        return f"u32::from({v})"
    if t in enums:
        return (
            "match "
            + v
            + " { "
            + ", ".join(
                name.replace("-", "_") + "_core::" + t + "::" + variant + " => " + str(i)
                for i, variant in enumerate(enums[t])
            )
            + " }"
        )
    if t in types:
        return f"self.{snake(t)}(&{v})"
    if t.startswith("Vec<"):
        return f"self.{snake(t[4:-1])}_list(&{v})"
    return v


def decode_expr(schema: Schema, t: str, v: str) -> str:
    name, types, enums = schema["name"], schema["types"], schema["enums"]
    if t == "String":
        return f"text({v})?"
    if t == "IpAddr":
        return f'text({v})?.parse().map_err(|_| invalid("invalid library IP address"))?'
    if t == "Option<String>":
        return f"maybe_text({v})?"
    if t == "Vec<u8>":
        return f"bytes({v})"
    if t == "Vec<String>":
        return f"strings({v})?"
    if t == "Option<u16>":
        return f"({v}.present != 0).then_some({v}.value)"
    if t == "bool":
        return f"{v} != 0"
    if t in enums:
        return (
            "match "
            + v
            + " { "
            + ", ".join(
                str(i) + " => " + name.replace("-", "_") + "_core::" + t + "::" + variant
                for i, variant in enumerate(enums[t])
            )
            + ', _ => return Err(invalid("unknown library enum")) }'
        )
    if t in types:
        return f"{snake(t)}(&{v})?"
    if t.startswith("Vec<"):
        return f"{snake(t[4:-1])}_list({v})?"
    return v


def generate_struct(
    schema: Schema, typ: str, definition: TypeDefinition
) -> tuple[list[str], list[str]]:
    view, decode = [], []
    fn = snake(typ)
    native = definition["rust"]
    fields = definition["fields"]
    view += (
        [f"pub(crate) fn {fn}(&mut self, value: &{native}) -> abi::{typ} {{ abi::{typ} {{"]
        + [f"{field}: {encode_expr(schema, t, 'value.' + field)}," for field, t in fields]
        + [
            "} }",
            f"pub(crate) fn {fn}_list(&mut self, values: &[{native}]) -> abi::{typ}List {{",
            f"let owned: Box<[_]> = values.iter().map(|value| self.{fn}(value)).collect();",
            f"let result = abi::{typ}List {{ data: owned.as_ptr(), len: owned.len() }};",
            "self.allocations.push(Box::new(owned)); result }",
        ]
    )
    target = native.replace("trust_client_core::", "crate::")
    decode += (
        [
            f"pub(crate) unsafe fn {fn}(value: &abi::{typ}) -> Result<{target}, Error> {{",
            "// SAFETY: the caller keeps the result and every nested allocation alive.",
            "#[allow(unused_unsafe)]",
            f"unsafe {{ Ok({target} {{",
        ]
        + [f"{field}: {decode_expr(schema, t, 'value.' + field)}," for field, t in fields]
        + [
            "}) } }",
            f"pub(crate) unsafe fn {fn}_list(value: abi::{typ}List) -> Result<Vec<{target}>, Error> {{",
            "// SAFETY: all elements and nested spans belong to the live result.",
            f"unsafe {{ array(value.data, value.len).iter().map(|value| {fn}(value)).collect() }} }}",
        ]
    )
    return view, decode


def generate(schema: Schema) -> dict[str, str]:
    name = schema["name"]
    rust, header = generate_layouts(schema)
    view, decode = generate_helpers(schema)
    for typ, definition in schema["types"].items():
        struct_view, struct_decode = generate_struct(schema, typ, definition)
        view.extend(struct_view)
        decode.extend(struct_decode)
    view += ["}"]
    roots = {snake(typ) for typ in schema["outputs"] if typ not in ("Text", "Bytes", "Boolean")}
    view = retain_functions("\n".join(view), roots | {"text", "maybe_text", "absent"}).splitlines()
    decode = retain_functions(
        "\n".join(decode), roots | {"text", "bytes", "maybe_text"}
    ).splitlines()
    return {
        f"{name}-abi/src/lib.rs": "\n".join(rust) + "\n",
        f"lib{name}/include/peios/{name}-types.h": "\n".join(header) + "\n",
        f"lib{name}/src/views.rs": "\n".join(view) + "\n",
        f"{name}-client/src/decode.rs": "\n".join(decode) + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    schemas = list((root / "tools").glob("*-api.json"))
    if len(schemas) != 1:
        raise SystemExit("expected one API schema")
    outputs = generate(cast(Schema, json.loads(schemas[0].read_text())))

    with tempfile.TemporaryDirectory(prefix="service-api-") as temporary:
        for path, text in outputs.items():
            generated = Path(temporary) / Path(path).name
            generated.write_text(text)
            if generated.suffix == ".rs":
                command = [
                    "rustup",
                    "run",
                    "1.98.1",
                    "rustfmt",
                    "--edition",
                    "2024",
                    "--config-path",
                    str(root / "rustfmt.toml"),
                ]
            else:
                command = [
                    str(Path(os.environ["PEIOS_STYLE_BIN"]) / "clang-format"),
                    "-i",
                    "--style=file:" + str(root / "tools/clang-format.yaml"),
                ]
            subprocess.run([*command, str(generated)], check=True)
            target = root / path
            if args.check:
                if target.read_bytes() != generated.read_bytes():
                    raise SystemExit(path + " is stale")
            else:
                target.write_bytes(generated.read_bytes())


if __name__ == "__main__":
    main()
